# seconddns-tsig on a real named with a Plesk-style named.conf: zones use
# allow-transfer { common-allow-transfer; }. After enable our IP needs the key; a Plesk
# rewrite (template ACL back, key gone) reopens our IP until restore puts the key back.
# named runs without chroot here (that needs root), so the key file sits next to the
# config. Requires: named, dig, python3. Skips itself when BIND is not installed.
#
# Usage: ./test_tsig_plesk_named.sh

set -u

for t in named named-checkconf dig; do
    command -v "$t" > /dev/null || { echo "skipped: $t not installed"; exit 0; }
done

HERE="$(cd "$(dirname "$0")" && pwd)"
TSIG="$HERE/../seconddns-tsig"
TMP="$(mktemp -d)"
API_PORT=8893
DNS_PORT=5302
CONF="$TMP/named.conf"

export SECONDDNS_TSIG_FLAVOR=plesk
export SECONDDNS_PLESK_CHROOT=""
export SECONDDNS_NAMED_OPTIONS="$CONF"
export SECONDDNS_CONF="$TMP/seconddns.conf"
export SECONDDNS_TSIG_SECRET="$TMP/etc-seconddns/tsig.secret"
export SECONDDNS_NAMED_CHECKCONF="named-checkconf $CONF"
export SECONDDNS_NAMED_RELOAD="sh -c 'kill -HUP \$(cat $TMP/named.pid) && sleep 1'"
export SECONDDNS_NAMED_GID="$(id -g)"
export SECONDDNS_QUEUED_RESTART="true"
export SECONDDNS_SYSTEMD_DIR="$TMP"
export SECONDDNS_SYSTEMCTL="true"

PASS=0; FAIL=0
ok()   { PASS=$((PASS+1)); echo "  ok: $1"; }
fail() { FAIL=$((FAIL+1)); echo "  FAIL: $1"; }

cat > "$TMP/a.example" <<'EOF'
$TTL 300
@   IN SOA ns1.a.example. hostmaster.a.example. 1 300 60 86400 60
@   IN NS  ns1.a.example.
ns1 IN A   192.0.2.53
www IN A   192.0.2.10
EOF
# our IP is 127.0.0.1, the customer's other secondary 127.0.0.2
template_acl='acl common-allow-transfer {
	127.0.0.2;
	127.0.0.1;
};'
cat > "$CONF" <<EOF
options {
	directory "$TMP";
	pid-file "$TMP/named.pid";
	listen-on port $DNS_PORT { 127.0.0.1; };
	listen-on-v6 { none; };
	recursion no;
};
zone "a.example" {
	type master;
	file "a.example";
	allow-transfer {
		common-allow-transfer;
	};
};
$template_acl
// -- END OF LINES GENERATED BY PLESK. --

// -- PLEASE ADD YOUR CUSTOM DIRECTIVES BELOW THIS LINE. --
// -- END OF YOUR CUSTOM DIRECTIVES. --
EOF
cat > "$SECONDDNS_CONF" <<EOF
[seconddns]
api_url = http://127.0.0.1:$API_PORT
api_key = test-key
master_ip = 192.0.2.10
EOF
SECRET=$(python3 -c 'import base64,os;print(base64.b64encode(os.urandom(32)).decode())')

python3 - "$API_PORT" > /dev/null 2>&1 <<'PYEOF' &
import http.server, sys, json
zones = [{"id": "z1", "name": "a.example", "masterIp": "192.0.2.10", "tsigKeyId": None}]
class H(http.server.BaseHTTPRequestHandler):
    def log_message(self, *a): pass
    def reply(self, code, body):
        self.send_response(code); self.send_header('Content-Type','application/json'); self.end_headers()
        self.wfile.write(json.dumps(body).encode())
    def do_GET(self):
        p = self.path.split('?')[0]
        if p == '/api/user/tsig-keys':
            self.reply(200, [{"id": "k1", "label": "web", "name": "acct-web", "algorithm": "hmac-sha256", "isDefault": False}])
        elif p == '/api/server-info': self.reply(200, {"dnsIps": "127.0.0.1"})
        elif p == '/api/zones': self.reply(200, zones)
        else: self.reply(404, {})
    def do_PATCH(self):
        body = json.loads(self.rfile.read(int(self.headers.get('Content-Length', 0))) or b'{}')
        for z in zones: z['tsigKeyId'] = body.get('tsigKeyId')
        self.reply(200, {})
http.server.HTTPServer(('127.0.0.1', int(sys.argv[1])), H).serve_forever()
PYEOF
API_PID=$!
disown $API_PID 2>/dev/null || true
named -c "$CONF" -g > "$TMP/named.log" 2>&1 &
NAMED_PID=$!
disown $NAMED_PID 2>/dev/null || true
trap 'kill $API_PID $NAMED_PID 2>/dev/null; rm -rf "$TMP"' EXIT
for i in $(seq 1 20); do dig +short -p $DNS_PORT @127.0.0.1 a.example SOA > /dev/null 2>&1 && break; sleep 0.5; done

transfers() { dig +tries=1 +time=3 -p $DNS_PORT @127.0.0.1 -b "$1" ${2:+-y "$2"} a.example AXFR 2>&1 | grep -q 'www.a.example.*192.0.2.10'; }
KEY="hmac-sha256:acct-web:$SECRET"

echo "== 0. before: our IP transfers by IP"
transfers 127.0.0.1 && ok "baseline" || fail "baseline broken"

echo "== 1. enable --zones"
"$TSIG" enable --tsig="web:$SECRET" --zones > "$TMP/out" 2>&1 || fail "enable: $(cat "$TMP/out")"
transfers 127.0.0.1 && fail "our IP still transfers without the key" || ok "our IP without the key is refused"
transfers 127.0.0.1 "$KEY" && ok "our IP with the key transfers" || fail "signed AXFR failed"
transfers 127.0.0.2 && ok "the customer's other secondary still transfers by IP" || fail "customer's secondary lost access"

echo "== 2. Plesk rewrites named.conf, then restore"
python3 - "$CONF" "$template_acl" <<'PY'
import re, sys
p, acl = sys.argv[1], sys.argv[2]; s = open(p).read()
open(p, "w").write(re.sub(r"acl common-allow-transfer \{.*?\};", acl, s, flags=re.S))
PY
kill -HUP "$(cat "$TMP/named.pid")"; sleep 1
transfers 127.0.0.1 && ok "right after the rewrite our IP is open again (the window)" || fail "rewrite simulation did not reopen our IP"
"$TSIG" restore > "$TMP/out" 2>&1 || fail "restore: $(cat "$TMP/out")"
transfers 127.0.0.1 && fail "restore left our IP open" || ok "after restore our IP needs the key again"
transfers 127.0.0.1 "$KEY" && ok "signed AXFR works after restore" || fail "signed AXFR failed after restore"

echo "== 3. disable --zones"
"$TSIG" disable --zones > "$TMP/out" 2>&1 || fail "disable: $(cat "$TMP/out")"
transfers 127.0.0.1 && ok "our IP transfers without a key again" || fail "our IP refused after disable"

echo
echo "passed: $PASS, failed: $FAIL"
[ "$FAIL" -eq 0 ]
